// 生成一份只缩放计时器、逻辑完全相同的 server 副本，用于快速跑完整局。
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');

const replacements = [
  ["const PREPARE_MS = 3000;", 'const PREPARE_MS = 300;'],
  ["const WORD_CHOOSE_MS = 10000;", 'const WORD_CHOOSE_MS = 1000;'],
  ["const RESULT_MS = 8000;", 'const RESULT_MS = 800;'],
  ["const PERFECT_RESULT_MS = 12000;", 'const PERFECT_RESULT_MS = 1200;'],
  ["const DRAWER_PAUSE_MS = 20000;", 'const DRAWER_PAUSE_MS = 2000;'],
  ["const RELAY_INTRO_MS = 3000;", 'const RELAY_INTRO_MS = 300;'],
  ["const RELAY_COLLECT_MS = 4000;", 'const RELAY_COLLECT_MS = 400;'],
  ["const RELAY_REVEAL_MS = 30000;", 'const RELAY_REVEAL_MS = 9000;'],
  ['Math.max(30, Number(msg.drawSeconds)', 'Math.max(5, Number(msg.drawSeconds)'],
  ['Math.max(15, Number(msg.guessSeconds)', 'Math.max(5, Number(msg.guessSeconds)'],
  ["const PUBLIC_DIR = path.join(__dirname, 'public');", "const PUBLIC_DIR = path.join(__dirname, '..', '..', 'public');"],
  ["const APP_DATA_DIR = path.resolve(process.env.DRAW_GUESS_DATA_DIR || path.join(__dirname, 'cache'));", "const APP_DATA_DIR = path.resolve(process.env.DRAW_GUESS_DATA_DIR || path.join(__dirname, '..', '..', 'cache'));"],
  ["from './words.js'", "from '../../words.js'"],
  ["from './word-packs.js'", "from '../../word-packs.js'"],
];

const src = await readFile(path.join(ROOT, 'server.js'), 'utf8');
let out = src;
for (const [from, to] of replacements) {
  if (!out.includes(from)) throw new Error(`replacement source not found: ${from}`);
  out = out.replace(from, to);
}
out = `// AUTO-GENERATED by tests/sim/make-fast-server.mjs — 只缩放计时/限流常量，逻辑与 server.js 一致\n${out}`;
await writeFile(path.join(__dirname, 'server-fast.mjs'), out, 'utf8');
console.log('server-fast.mjs written');
